import { describe, expect, it } from 'vitest'
import { buildDiff, truncatePatch } from '../src/diff/budget.js'
import {
  categorize,
  filterFiles,
  looksGenerated,
  type KeptFile,
  type PrFile
} from '../src/diff/filter.js'
import { loadFixture } from './support/fakes.js'

describe('filterFiles', () => {
  const files = loadFixture('feature-pr.json')

  it('drops lockfiles, build output, binaries and generated code', () => {
    const { kept, excluded } = filterFiles(files, [])
    expect(kept.map(f => f.filename)).toEqual([
      'src/http/client.ts',
      'src/http/client.test.ts',
      'docs/retries.md',
      'src/legacy/poller.ts'
    ])
    expect(excluded).toEqual([
      { filename: 'src/api/schema.ts', reason: 'generated' },
      { filename: 'package-lock.json', reason: 'path' },
      { filename: 'dist/index.js', reason: 'path' },
      { filename: 'assets/logo.png', reason: 'binary' }
    ])
  })

  it('applies user patterns after the defaults, with "!" re-including files', () => {
    const { kept } = filterFiles(files, ['docs/**', '!dist/**'])
    const names = kept.map(f => f.filename)
    expect(names).not.toContain('docs/retries.md')
    expect(names).toContain('dist/index.js')
  })

  it('matches default globs at any depth', () => {
    const nested: PrFile[] = [
      {
        filename: 'packages/web/yarn.lock',
        status: 'modified',
        additions: 5,
        deletions: 1,
        changes: 6,
        patch: '@@'
      },
      {
        filename: 'packages/web/src/app.ts',
        status: 'modified',
        additions: 5,
        deletions: 1,
        changes: 6,
        patch: '@@'
      }
    ]
    expect(filterFiles(nested, []).kept.map(f => f.filename)).toEqual(['packages/web/src/app.ts'])
  })
})

describe('categorize', () => {
  it.each([
    ['src/http/client.ts', 'source'],
    ['src/http/client.test.ts', 'test'],
    ['pkg/server/handler_test.go', 'test'],
    ['tests/test_api.py', 'test'],
    ['README.md', 'docs'],
    ['docs/guide/setup.txt', 'docs'],
    ['.github/workflows/ci.yml', 'config'],
    ['tsconfig.json', 'config'],
    ['vite.config.ts', 'config'],
    ['Dockerfile', 'config'],
    ['app/models/user.rb', 'source']
  ])('%s is %s', (file, category) => {
    expect(categorize(file)).toBe(category)
  })
})

describe('looksGenerated', () => {
  it('detects common generated-code banners', () => {
    expect(looksGenerated('@@ -0,0 +1 @@\n+// Code generated by protoc-gen-go. DO NOT EDIT.')).toBe(
      true
    )
    expect(looksGenerated('@@ -0,0 +1 @@\n+# @generated by tool')).toBe(true)
    expect(looksGenerated('@@ -0,0 +1 @@\n+export const x = 1')).toBe(false)
    expect(looksGenerated(undefined)).toBe(false)
  })
})

function file(
  filename: string,
  patch: string,
  category: KeptFile['category'] = 'source'
): KeptFile {
  const lines = patch.split('\n').filter(l => l.startsWith('+') || l.startsWith('-')).length
  return {
    filename,
    status: 'modified',
    additions: lines,
    deletions: 0,
    changes: lines,
    patch,
    category
  }
}

function hunks(count: number, linesPerHunk: number): string {
  return Array.from({ length: count }, (_, h) =>
    [
      `@@ -${h * 100},${linesPerHunk} +${h * 100},${linesPerHunk} @@`,
      ...Array.from({ length: linesPerHunk }, (_, i) => `+line ${h}.${i} ${'x'.repeat(40)}`)
    ].join('\n')
  ).join('\n')
}

describe('buildDiff', () => {
  it('puts source before tests, config and docs, and lists every file in the overview', () => {
    const { kept } = filterFiles(loadFixture('feature-pr.json'), [])
    const digest = buildDiff(kept, 40_000)
    const order = [
      '=== src/http/client.ts',
      '=== src/http/client.test.ts',
      '=== docs/retries.md'
    ].map(h => digest.text.indexOf(h))
    expect(order.every(i => i >= 0)).toBe(true)
    expect([...order].sort((a, b) => a - b)).toEqual(order)
    expect(digest.text).toContain(
      '- src/legacy/poller.ts: source, removed, +0 -41 [deleted, contents not shown]'
    )
    expect(digest.text).not.toContain('export function poll')
    expect(digest.changedLines).toBe(28 + 6 + 19 + 6 + 41)
    expect(digest.sourceFiles).toEqual(['src/http/client.ts', 'src/legacy/poller.ts'])
    expect(digest.truncatedFiles).toEqual([])
    expect(digest.hash).toMatch(/^sha256:[0-9a-f]{32}$/)
  })

  it('stays within the budget and says what was cut', () => {
    const files = [
      file('src/big.ts', hunks(40, 20)),
      file('src/other.ts', hunks(5, 10)),
      file('src/third.ts', hunks(30, 20)),
      file('test/big.test.ts', hunks(30, 20), 'test')
    ]
    const digest = buildDiff(files, 20_000)
    expect(digest.text.length).toBeLessThanOrEqual(20_000)
    expect(digest.includedFiles[0]).toBe('src/big.ts')
    expect(digest.truncatedFiles).toContain('src/big.ts')
    expect(digest.text).toMatch(/more hunk\(s\) truncated/)
    expect(digest.omittedFiles.length + digest.truncatedFiles.length).toBeGreaterThan(1)
    expect(digest.text).toContain('[Truncated to fit the size limit:')
  })

  it('keeps the same fingerprint for the same diff, whatever the file order', () => {
    const a = file('src/a.ts', '@@ -1 +1 @@\n+a')
    const b = file('src/b.ts', '@@ -1 +1 @@\n+b')
    expect(buildDiff([a, b], 10_000).hash).toBe(buildDiff([b, a], 10_000).hash)
    expect(buildDiff([a], 10_000).hash).not.toBe(buildDiff([a, b], 10_000).hash)
  })
})

describe('truncatePatch', () => {
  it('returns short patches untouched', () => {
    expect(truncatePatch('@@ -1 +1 @@\n+x', 100)).toEqual({
      body: '@@ -1 +1 @@\n+x',
      truncated: false
    })
  })

  it('cuts at hunk boundaries when possible', () => {
    const patch = hunks(10, 10)
    const { body, truncated } = truncatePatch(patch, 2_000)
    expect(truncated).toBe(true)
    expect(body.length).toBeLessThanOrEqual(2_000)
    expect(body.split('\n').filter(l => l.startsWith('@@')).length).toBeGreaterThan(0)
    expect(body).toMatch(/\[\d+ more hunk\(s\) truncated\]$/)
  })

  it('cuts inside a single huge hunk', () => {
    const { body, truncated } = truncatePatch(hunks(1, 500), 1_000)
    expect(truncated).toBe(true)
    expect(body.length).toBeLessThanOrEqual(1_000)
    expect(body.endsWith('... [truncated]')).toBe(true)
  })
})
